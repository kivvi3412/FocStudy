// ============================================================================
// Fast Trigonometric LUT
//
// 512-point full-period sine table + linear interpolation
//
// Typical interpolation error:
//   Maximum absolute error ~1.9e-5
//
// Memory:
//   513 * sizeof(float) = 2052 bytes
//
// Recommended FOC usage:
//
//   float s, c;
//   fast_sincosf(theta, &s, &c);
//
// Or:
//
//   float s = fast_sinf(theta);
//   float c = fast_cosf(theta);
//
// Notes:
//   1. Table is placed in DRAM using DRAM_ATTR.
//   2. Fast-path functions are placed in IRAM using IRAM_ATTR.
//   3. fast_sincosf() is faster than separately calling sin + cos because
//      angle normalization/index calculation is performed only once.
//   4. Extremely large / NaN / Inf inputs fall back to libm sinf/cosf.
